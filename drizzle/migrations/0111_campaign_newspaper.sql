CREATE OR REPLACE FUNCTION public.can_edit_campaign_newspaper()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, pg_temp AS $$
  SELECT auth.uid() IS NOT NULL
    AND (
      public.is_campaign_admin()
      OR EXISTS (
        SELECT 1 FROM public.campaign_players p
        WHERE p.user_id = auth.uid()
          AND p.active IS TRUE
          AND p.require_password_change IS FALSE
          AND lower(btrim(p.name)) = 'leonardo'
          AND p.roster_house_id = 'espiao'
      )
    );
$$;
REVOKE ALL ON FUNCTION public.can_edit_campaign_newspaper() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.can_edit_campaign_newspaper() TO authenticated;

CREATE OR REPLACE FUNCTION public.can_read_campaign_newspaper_player()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, pg_temp AS $$
  SELECT auth.uid() IS NOT NULL AND EXISTS (
    SELECT 1 FROM public.campaign_players p
    WHERE p.user_id = auth.uid()
      AND p.active IS TRUE
      AND p.require_password_change IS FALSE
  );
$$;
REVOKE ALL ON FUNCTION public.can_read_campaign_newspaper_player() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.can_read_campaign_newspaper_player() TO authenticated;

CREATE TABLE IF NOT EXISTS public.campaign_newspapers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  edition_no bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  campaign_date text NOT NULL CHECK (campaign_date ~ '^([0-9]{4}-[0-9]{2}-[0-9]{2}|[0-9]{4}-F-[a-z-]+)$'),
  title text NOT NULL DEFAULT 'Gazeta de Cormyr' CHECK (length(title) BETWEEN 1 AND 180),
  subtitle text NOT NULL DEFAULT '' CHECK (length(subtitle) <= 240),
  template text NOT NULL DEFAULT 'classico' CHECK (template IN ('classico','guerra','gazeta')),
  font_style text NOT NULL DEFAULT 'classico' CHECK (font_style IN ('classico','editorial','condensado')),
  state text NOT NULL DEFAULT 'draft' CHECK (state IN ('draft','published','archived','cancelled')),
  blocks jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(blocks) = 'array' AND jsonb_array_length(blocks) <= 80),
  pdf_path text,
  version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
  created_by uuid NOT NULL DEFAULT auth.uid(),
  updated_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz,
  archived_at timestamptz,
  cancelled_at timestamptz,
  CONSTRAINT newspaper_pdf_path CHECK (
    pdf_path IS NULL OR (pdf_path LIKE id::text || '/%.pdf' AND length(pdf_path) <= 300)
  )
);
CREATE INDEX IF NOT EXISTS campaign_newspapers_published_idx
  ON public.campaign_newspapers (published_at DESC)
  WHERE state IN ('published','archived');

CREATE TABLE IF NOT EXISTS public.campaign_newspaper_revisions (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  newspaper_id uuid NOT NULL REFERENCES public.campaign_newspapers(id),
  previous_version integer NOT NULL,
  snapshot jsonb NOT NULL,
  changed_by uuid,
  changed_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS newspaper_revisions_edition_idx
  ON public.campaign_newspaper_revisions (newspaper_id, previous_version DESC);

CREATE TABLE IF NOT EXISTS public.campaign_newspaper_reads (
  newspaper_id uuid NOT NULL REFERENCES public.campaign_newspapers(id),
  user_id uuid NOT NULL,
  read_version integer NOT NULL,
  read_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(newspaper_id,user_id)
);

CREATE OR REPLACE FUNCTION public.stamp_campaign_newspaper()
RETURNS trigger LANGUAGE plpgsql SET search_path=public,pg_temp AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.created_by := auth.uid();
    NEW.updated_by := auth.uid();
    NEW.version := 1;
    IF NEW.state <> 'draft' THEN
      RAISE EXCEPTION 'A nova edição deve começar como rascunho.';
    END IF;
  ELSE
    IF NEW.id <> OLD.id OR NEW.edition_no <> OLD.edition_no
       OR NEW.created_by <> OLD.created_by THEN
      RAISE EXCEPTION 'Identidade da edição é imutável.';
    END IF;
    NEW.version := OLD.version + 1;
    NEW.updated_by := auth.uid();
  END IF;
  NEW.updated_at := now();
  IF NEW.state = 'published' AND
     (TG_OP = 'INSERT' OR OLD.state <> 'published') THEN
    NEW.published_at := now();
  END IF;
  IF NEW.state = 'archived' AND
     (TG_OP = 'INSERT' OR OLD.state <> 'archived') THEN
    NEW.archived_at := now();
  END IF;
  IF NEW.state = 'cancelled' AND
     (TG_OP = 'INSERT' OR OLD.state <> 'cancelled') THEN
    NEW.cancelled_at := now();
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS stamp_campaign_newspaper_trigger ON public.campaign_newspapers;
CREATE TRIGGER stamp_campaign_newspaper_trigger BEFORE INSERT OR UPDATE
 ON public.campaign_newspapers FOR EACH ROW
 EXECUTE FUNCTION public.stamp_campaign_newspaper();

CREATE OR REPLACE FUNCTION public.audit_campaign_newspaper()
RETURNS trigger LANGUAGE plpgsql SET search_path=public,pg_temp AS $$
BEGIN
  INSERT INTO public.campaign_newspaper_revisions
    (newspaper_id,previous_version,snapshot,changed_by)
  VALUES (OLD.id,OLD.version,to_jsonb(OLD),auth.uid());
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS audit_campaign_newspaper_trigger ON public.campaign_newspapers;
CREATE TRIGGER audit_campaign_newspaper_trigger AFTER UPDATE
 ON public.campaign_newspapers FOR EACH ROW
 EXECUTE FUNCTION public.audit_campaign_newspaper();

