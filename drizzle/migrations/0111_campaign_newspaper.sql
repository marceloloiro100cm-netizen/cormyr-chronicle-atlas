CREATE OR REPLACE FUNCTION public.can_read_campaign_newspaper_asset(p_path text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER
SET search_path=public,pg_temp AS $$
  SELECT auth.uid() IS NOT NULL AND EXISTS (
    SELECT 1 FROM public.campaign_newspapers n
    WHERE p_path LIKE n.id::text || '/%'
      AND (
        public.can_edit_campaign_newspaper()
        OR (
          n.state IN ('published','archived')
          AND public.can_read_campaign_newspaper_player()
          AND (
            n.pdf_path = p_path
            OR EXISTS (
              SELECT 1 FROM jsonb_array_elements(n.blocks) b
               WHERE b->>'imagePath' = p_path
            )
          )
        )
      )
  );
$$;
REVOKE ALL ON FUNCTION public.can_read_campaign_newspaper_asset(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.can_read_campaign_newspaper_asset(text) TO authenticated;

